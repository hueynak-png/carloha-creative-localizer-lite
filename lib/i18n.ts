export type TextKey = keyof typeof text.en;

export function getText(language: Language, key: TextKey) {
  return text[language][key];
}

export function getOptionLabel(language: Language, value: string) {
  return optionLabels[language][value] ?? value;
}

export function getWorkflowLabel(language: Language, workflowType: LocalizationTask["workflowType"]) {
  if (workflowType === "localize_existing") {
    return getText(language, "localizeExistingPoster");
  }
  return getText(language, "createNewPoster");
}
